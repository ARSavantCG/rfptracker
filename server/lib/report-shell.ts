/**
 * THE report layout. Every printable report uses this header and footer.
 *
 * Each report used to carry its own copy of the same block — logo, a
 * "Generated <date>" in the corner, the blue banner, one or two grey subtitle
 * lines — and the copies had drifted: 22px banners here, 24px there,
 * different margins, a scope line in some, a badge in one, an RFP's property
 * printed as its database ID in another. None said who had run it.
 *
 * The layout, as Adolfo marked it up on the Budget by Contract report
 * (2026-10-20):
 *
 *     [logo]
 *                    EVALUATION REPORT              <- eyebrow: which family
 *     [=========== Budget by Contract ===========]  <- banner: which report
 *     Tenant     APM Logistics & Transportation, LLC (RFP-2026-031)
 *     Property   Kurv Doral II – Bldg. 2    Rentable Area   52,140 SF
 *     ...body...
 *     Generated by Adolfo Reutlinger on October 20, 2026 at 1:12 PM ET
 *
 * The facts that used to be scattered through subtitle lines live in ONE
 * compact table, two pairs to a row, so a report spends its first inch on
 * what it is about rather than on whitespace.
 *
 * Pure: no database import, so it can be rendered and tested on its own.
 */
import { getBrandLogo, BRAND_COLOR_PRIMARY, COMPANY_NAME } from './branding';
import { resolveRfpRentableArea } from '@shared/area-utils';

export function escapeHtml(s: unknown): string {
  return String(s ?? '')
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/** Money to the cent. Reports show cents so line items visibly add up. */
export function money2(n: number): string {
  const v = Number.isFinite(n) ? n : 0;
  return v.toLocaleString('en-US', {
    style: 'currency', currency: 'USD', minimumFractionDigits: 2, maximumFractionDigits: 2,
  });
}

export function fmtSf(n: number): string {
  return `${Math.round(Number.isFinite(n) ? n : 0).toLocaleString('en-US')} SF`;
}

/** One fact in the info table. `wide` takes the whole row (long tenant names). */
export interface ReportInfoRow {
  label: string;
  value: string;
  wide?: boolean;
}

export interface ReportShellOptions {
  /** The banner: which report this is. */
  title: string;
  /** Small line above the banner: which family it belongs to. */
  eyebrow?: string;
  /** The at-a-glance facts. Values are escaped here; pass plain text. */
  info?: ReportInfoRow[];
  /** Short qualifications — "3 archived records excluded." Plain text. */
  notes?: string[];
  /** Who ran it. */
  generatedBy?: string | null;
  generatedAt?: Date;
}

/** Display name for the "Generated by" line, from whatever the session holds. */
export function generatedByName(user: any): string {
  if (!user) return '';
  const full = [user.firstName, user.lastName].filter(Boolean).join(' ').trim();
  return String(user.name || full || user.email || user.username || '').trim();
}

/** "October 20, 2026 at 1:12 PM ET" — always Eastern, where the team works. */
export function formatGeneratedAt(d: Date = new Date()): string {
  const date = d.toLocaleDateString('en-US', {
    timeZone: 'America/New_York', year: 'numeric', month: 'long', day: 'numeric',
  });
  const time = d.toLocaleTimeString('en-US', {
    timeZone: 'America/New_York', hour: 'numeric', minute: '2-digit',
  });
  return `${date} at ${time} ET`;
}

