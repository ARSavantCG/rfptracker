/** Logo, eyebrow, banner, rule, info table, notes. */
export function reportHeaderHtml(opts: ReportShellOptions): string {
  const logo = getBrandLogo();
  const info = (opts.info || []).filter((r) => r && String(r.value ?? '').trim() !== '');
  const notes = (opts.notes || []).filter((n) => String(n ?? '').trim() !== '');

  return `
  <header class="rs-header">
    <div class="rs-top">
      ${logo ? `<img class="rs-logo" src="${logo}" alt="${escapeHtml(COMPANY_NAME)}" />` : `<strong>${escapeHtml(COMPANY_NAME)}</strong>`}
    </div>
    ${opts.eyebrow ? `<div class="rs-eyebrow">${escapeHtml(opts.eyebrow)}</div>` : ''}
    <div class="rs-banner">${escapeHtml(opts.title)}</div>
    <hr class="rs-rule" />
    ${info.length ? `<dl class="rs-info">${info.map((r) =>
      `<dt>${escapeHtml(r.label)}</dt><dd${r.wide ? ' class="rs-wide"' : ''}>${escapeHtml(r.value)}</dd>`,
    ).join('')}</dl>` : ''}
    ${notes.length ? `<div class="rs-notes">${notes.map((n) => `<p>${escapeHtml(n)}</p>`).join('')}</div>` : ''}
  </header>`;
}

/** "Generated by … on …" and the company name. */
export function reportFooterHtml(opts: Pick<ReportShellOptions, 'generatedBy' | 'generatedAt'>): string {
  const who = String(opts.generatedBy ?? '').trim();
  const when = formatGeneratedAt(opts.generatedAt ?? new Date());
  return `
  <footer class="rs-footer">
    <span>Generated ${who ? `by ${escapeHtml(who)} ` : ''}on ${escapeHtml(when)}</span>
    <span>${escapeHtml(COMPANY_NAME)}</span>
  </footer>`;
}

// ---------------------------------------------------------------- per-RFP

/** "Kurv Doral II – Bldg. 2", or the names of every building on a multi-building RFP. */
export function rfpPropertyLabel(rfp: any, property: any | null | undefined): string {
  if (rfp?.isMultiBuilding && Array.isArray(rfp.properties) && rfp.properties.length) {
    return rfp.properties.join(', ');
  }
  if (property) {
    const building = String(property.building ?? '').trim();
    return building ? `${property.propertyName} – Bldg. ${building}` : String(property.propertyName ?? '');
  }
  // rfp.property holds the property ID. Printing it raw is how a report ended
  // up reading "Property: 9". Better to say nothing than to say that.
  const raw = String(rfp?.property ?? '').trim();
  return /^\d+$/.test(raw) ? '' : raw;
}

/**
 * The tenant's rentable area, by the same rule the evaluation screen uses:
 * the selected bays first (with the prorated mechanical room), then the
 * warehouse area typed on the RFP. Matching the screen matters — the design
 * fee is a rate per SF of exactly this number.
 */
export function rfpRentableSf(rfp: any, property: any | null | undefined): number {
  const bays = rfp?.selectedBayConfigurations;
  if (Array.isArray(bays) && bays.length) {
    const fromBays = resolveRfpRentableArea({
      selectedBays: bays,
      allPropertyBays: property?.bayConfigurations,
      mechanicalRoomSf: property?.mechanicalRoomSquareFootage,
      propertyName: property?.propertyName,
      propertyId: property?.id,
    }).rentableSf;
    if (fromBays > 0) return fromBays;
  }
  const typed = parseFloat(String(rfp?.warehouseArea ?? rfp?.projectArea ?? '').replace(/[^0-9.]/g, ''));
  return Number.isFinite(typed) ? Math.round(typed) : 0;
}

/** Tenant (with RFP number), Property, Rentable Area — the per-RFP header. */
export function rfpInfoRows(rfp: any, property: any | null | undefined): ReportInfoRow[] {
  const tenant = String(rfp?.tenantName ?? '').trim();
  const number = String(rfp?.rfpNumber ?? '').trim();
  const sf = rfpRentableSf(rfp, property);
  return [
    { label: 'Tenant', value: number ? `${tenant} (${number})` : tenant, wide: true },
    { label: 'Property', value: rfpPropertyLabel(rfp, property) },
    { label: 'Rentable Area', value: sf > 0 ? fmtSf(sf) : '' },
  ];
}
